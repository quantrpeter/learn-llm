# ═══════════════════════════════════════════════════════════════════════════
# PART 4 — SFT TRAINING (loss masking)
# ═══════════════════════════════════════════════════════════════════════════
#
# SFT uses the exact same cross-entropy loss as pre-training, but with
# a critical difference: we MASK the loss on non-assistant tokens.
#
# Why?  We don't want the model to learn to predict system prompts or
# user messages.  We only want it to learn: "given this context, produce
# THIS assistant response."
#
# Implementation: set loss labels to -100 for tokens we want to ignore.
# PyTorch's CrossEntropyLoss ignores targets with value -100.
# ═══════════════════════════════════════════════════════════════════════════

print("\n" + "=" * 72)
print("PART 4: SFT TRAINING — Loss Masking on Assistant Tokens")
print("=" * 72)

torch.manual_seed(42)

"""
WHY THIS MATTERS:
If you train on ALL tokens (including system/user), the model wastes
capacity learning to mimic user questions.  Masking ensures every
gradient update pushes the model toward better RESPONSES only.
This is the single most important implementation detail in SFT.
"""


# --- 4.1 Build a toy SFT example -----------------------------------------

IGNORE_INDEX = -100
vocab_size = 32
seq_len = 20

# Simulate token IDs for a conversation
token_ids = torch.randint(0, vocab_size, (seq_len,))

# Mark which positions are assistant tokens (1 = assistant, 0 = other)
# Positions 0-7: system/user prompt, 8-14: assistant response, 15-19: padding
is_assistant = torch.zeros(seq_len, dtype=torch.bool)
is_assistant[8:15] = True   # only assistant response positions

# Build labels: shift by 1 (predict next token), mask non-assistant
labels = torch.full((seq_len,), IGNORE_INDEX, dtype=torch.long)
labels[8:15] = token_ids[9:16]  # next-token targets for assistant positions

print(f"\nToken IDs:     {token_ids.tolist()}")
print(f"Is assistant:  {is_assistant.int().tolist()}")
print(f"Labels:        {labels.tolist()}")
print(f"  -100 = masked (no loss), other = target token ID")
print(f"  {(labels != IGNORE_INDEX).sum().item()} out of {seq_len} tokens contribute to loss")


# --- 4.2 SFT loss computation with masking --------------------------------

class TinySFTModel(nn.Module):
    """Minimal model to demonstrate SFT loss masking."""

    def __init__(self, vocab_size, d_model=64):
        super().__init__()
        self.embed = nn.Embedding(vocab_size, d_model)
        self.head = nn.Linear(d_model, vocab_size)

    def forward(self, input_ids):
        return self.head(self.embed(input_ids))


model = TinySFTModel(vocab_size)
logits = model(token_ids.unsqueeze(0)).squeeze(0)  # (seq_len, vocab_size)

# Standard cross-entropy ignores targets == -100
loss_fn = nn.CrossEntropyLoss(ignore_index=IGNORE_INDEX)
sft_loss = loss_fn(logits, labels)

# Compare with naive loss on ALL tokens (wrong approach)
naive_labels = token_ids[1:].clone()  # next-token for every position
naive_labels = F.pad(naive_labels, (0, 1), value=0)
naive_loss = loss_fn(logits, naive_labels)

print(f"\nSFT loss (assistant only):  {sft_loss.item():.4f}")
print(f"Naive loss (all tokens):    {naive_loss.item():.4f}")
print(f"  → SFT focuses gradients on what matters: the response quality.")


# --- 4.3 Full SFT training loop ------------------------------------------

torch.manual_seed(42)
model = TinySFTModel(vocab_size)
optimizer = torch.optim.AdamW(model.parameters(), lr=1e-3)

# Create a mini SFT "dataset" — 8 conversation samples
batch_size = 8
input_batch = torch.randint(0, vocab_size, (batch_size, seq_len))
label_batch = torch.full((batch_size, seq_len), IGNORE_INDEX, dtype=torch.long)

# For each sample, mark positions 8-14 as assistant (same pattern)
for i in range(batch_size):
    label_batch[i, 8:15] = input_batch[i, 9:16]

print(f"\n--- SFT Training Loop ---")
print(f"Batch: {batch_size} samples × {seq_len} tokens")
print(f"Assistant tokens per sample: 7")
print(f"Total trainable tokens per batch: {batch_size * 7}")

num_steps = 100
for step in range(num_steps):
    logits = model(input_batch)                              # (B, T, V)
    loss = loss_fn(logits.view(-1, vocab_size), label_batch.view(-1))
    loss.backward()
    optimizer.step()
    optimizer.zero_grad()

    if step % 20 == 0 or step == num_steps - 1:
        print(f"  Step {step:3d} | Loss: {loss.item():.4f} | "
              f"PPL: {torch.exp(loss).item():.1f}")

print(f"\n  Started at PPL ≈ {vocab_size} (random over {vocab_size} tokens)")
print(f"  → Loss drops = model learns assistant response patterns.")


# ═══════════════════════════════════════════════════════════════════════════
# PART 5 — LoRA (Low-Rank Adaptation) FROM SCRATCH
# ═══════════════════════════════════════════════════════════════════════════
#
# Full fine-tuning updates ALL parameters.  For a 7B model that's 14 GB
# of gradients + 56 GB of optimizer states = too much memory.
#
# LoRA's insight: the weight UPDATE during fine-tuning is low-rank.
# Instead of updating W directly, learn two small matrices A and B:
#
#     W' = W + (B @ A)    where W is (d, d), A is (d, r), B is (r, d)
#                          r << d  (e.g., r=16 vs d=4096)
#
# Initialization:
#   - A: random normal (so gradients flow from the start)
#   - B: zeros (so W' = W at initialization — no disruption)
#
# Only A and B are trained.  W is frozen.
# ═══════════════════════════════════════════════════════════════════════════

print("\n" + "=" * 72)
print("PART 5: LoRA — Low-Rank Adaptation FROM SCRATCH")
print("=" * 72)

torch.manual_seed(42)

"""
WHY THIS MATTERS:
LoRA made fine-tuning accessible.  Before LoRA, fine-tuning a 7B model
required 80+ GB of GPU memory.  With LoRA (rank=16), you need < 16 GB.
It's the standard approach for customizing LLMs today.
"""


# --- 5.1 LoRA layer implementation ----------------------------------------

class LoRALinear(nn.Module):
    """
    Wraps an existing nn.Linear with Low-Rank Adaptation.

    Forward:  y = W @ x + (B @ A) @ x * (alpha / r)

    W is frozen.  Only A and B are trainable.
    alpha/r is a scaling factor to control the magnitude of the adaptation.
    """

    def __init__(self, base_linear: nn.Linear, rank: int = 16, alpha: float = 16.0):
        super().__init__()
        self.base = base_linear
        self.rank = rank
        self.alpha = alpha

        in_features = base_linear.in_features
        out_features = base_linear.out_features

        # A: (rank, in_features) — initialized with random normal
        self.lora_A = nn.Parameter(torch.randn(rank, in_features) * 0.01)
        # B: (out_features, rank) — initialized with zeros
        self.lora_B = nn.Parameter(torch.zeros(out_features, rank))

        # Freeze the base weights
        self.base.weight.requires_grad = False
        if self.base.bias is not None:
            self.base.bias.requires_grad = False

    def forward(self, x):
        base_out = self.base(x)
        # LoRA path: x @ A^T @ B^T  (equivalent to (B @ A) @ x)
        lora_out = (x @ self.lora_A.T) @ self.lora_B.T
        scaling = self.alpha / self.rank
        return base_out + lora_out * scaling


# --- 5.2 Verify zero-init means no disruption ----------------------------

d_model = 256
base_linear = nn.Linear(d_model, d_model)
lora_layer = LoRALinear(base_linear, rank=16, alpha=16.0)

x = torch.randn(2, 10, d_model)  # (batch, seq_len, d_model)
base_out = base_linear(x)
lora_out = lora_layer(x)

diff = (base_out - lora_out).abs().max().item()
print(f"\nMax difference at init (should be 0): {diff:.10f}")
print(f"  → B is zeros, so B @ A = 0.  LoRA starts as identity adapter.")


# --- 5.3 Parameter savings -----------------------------------------------

print(f"\n--- Parameter Savings ---")

original_params = d_model * d_model
print(f"Original Linear({d_model}, {d_model}): {original_params:,} params")

for rank in [4, 8, 16, 32, 64]:
    lora_params = rank * d_model + d_model * rank  # A + B
    ratio = lora_params / original_params * 100
    print(f"  LoRA rank={rank:2d}: {lora_params:>8,} params ({ratio:5.2f}% of original)")


# --- 5.4 Scaling to real models -------------------------------------------

print(f"\n--- LoRA on a 7B Model (LLaMA-2 7B) ---")

d = 4096
n_layers = 32
n_targets = 4    # Q, K, V, O projections in each layer

total_model = 7_000_000_000
full_ft_trainable = total_model

for rank in [8, 16, 32, 64]:
    lora_per_target = rank * d + d * rank   # A + B for one Linear
    total_lora = lora_per_target * n_targets * n_layers
    pct = total_lora / total_model * 100

    full_ft_mem = full_ft_trainable * 2 / 1e9      # FP16 params
    full_ft_opt = full_ft_trainable * (4 + 4) / 1e9  # Adam: momentum + variance
    lora_opt = total_lora * (4 + 4) / 1e9

    print(f"\n  Rank {rank:2d}:")
    print(f"    Trainable:    {total_lora:>12,} ({pct:.2f}% of 7B)")
    print(f"    LoRA memory:  {total_lora * 2 / 1e9:.2f} GB (params in FP16)")
    print(f"    Optimizer:    {lora_opt:.2f} GB (vs {full_ft_opt:.1f} GB for full FT)")


# --- 5.5 Training a LoRA model -------------------------------------------

print(f"\n--- Training LoRA vs Full Fine-Tune ---")
torch.manual_seed(42)

d_model = 128
num_classes = 10
batch_size = 32
seq_len = 16

# Pretrained base: a simple 2-layer transformer-ish model
class TinyModel(nn.Module):
    def __init__(self):
        super().__init__()
        self.embed = nn.Embedding(100, d_model)
        self.attn_proj = nn.Linear(d_model, d_model)
        self.ffn1 = nn.Linear(d_model, d_model * 4)
        self.ffn2 = nn.Linear(d_model * 4, d_model)
        self.head = nn.Linear(d_model, num_classes)

    def forward(self, x):
        h = self.embed(x)
        h = h + F.gelu(self.attn_proj(h))
        h = h + self.ffn2(F.gelu(self.ffn1(h)))
        return self.head(h.mean(dim=1))


# Synthetic dataset
input_ids = torch.randint(0, 100, (batch_size, seq_len))
targets = torch.randint(0, num_classes, (batch_size,))

# Full fine-tune
model_full = TinyModel()
opt_full = torch.optim.AdamW(model_full.parameters(), lr=1e-3)
loss_fn = nn.CrossEntropyLoss()

# LoRA fine-tune (only adapt attn_proj and ffn1)
model_lora = TinyModel()
model_lora.load_state_dict(model_full.state_dict())
model_lora.attn_proj = LoRALinear(model_lora.attn_proj, rank=8)
model_lora.ffn1 = LoRALinear(model_lora.ffn1, rank=8)
# Freeze everything except LoRA parameters
for name, param in model_lora.named_parameters():
    if "lora_" not in name:
        param.requires_grad = False
opt_lora = torch.optim.AdamW(
    [p for p in model_lora.parameters() if p.requires_grad], lr=1e-3
)

full_trainable = sum(p.numel() for p in model_full.parameters() if p.requires_grad)
lora_trainable = sum(p.numel() for p in model_lora.parameters() if p.requires_grad)
print(f"\nFull FT trainable: {full_trainable:,} params")
print(f"LoRA trainable:    {lora_trainable:,} params ({lora_trainable/full_trainable*100:.1f}%)")

print(f"\n  {'Step':>4s}  {'Full FT Loss':>13s}  {'LoRA Loss':>10s}")
print(f"  {'─'*4:>4s}  {'─'*13:>13s}  {'─'*10:>10s}")

for step in range(60):
    # Full FT step
    logits_f = model_full(input_ids)
    loss_f = loss_fn(logits_f, targets)
    loss_f.backward()
    opt_full.step()
    opt_full.zero_grad()

    # LoRA step
    logits_l = model_lora(input_ids)
    loss_l = loss_fn(logits_l, targets)
    loss_l.backward()
    opt_lora.step()
    opt_lora.zero_grad()

    if step % 10 == 0 or step == 59:
        print(f"  {step:4d}  {loss_f.item():13.4f}  {loss_l.item():10.4f}")

print(f"\n  → LoRA trains {full_trainable/lora_trainable:.0f}x fewer params but converges comparably!")


