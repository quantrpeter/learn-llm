# --- 6.3 QLoRA key innovations -------------------------------------------

print(f"\n--- QLoRA Key Innovations ---")
print(f"""
  1. NF4 (Normal Float 4-bit)
     - Quantization levels are spaced for normal distributions
     - Neural network weights ARE approximately normal
     - Better than uniform INT4 for model weights

  2. Double Quantization
     - Quantize the quantization constants themselves
     - Saves ~0.4 bits per parameter (small but it adds up)

  3. Paged Optimizers
     - Offload optimizer states to CPU when GPU OOM
     - Automatic, transparent paging (like virtual memory)
     - Handles memory spikes during gradient checkpointing

  4. Training Recipe
     - Base weights: NF4 quantized (frozen)
     - LoRA adapters: BF16 (trainable)
     - Forward: dequantize on-the-fly for matmul
     - Backward: gradients flow through dequantized weights to LoRA
""")


