# PART 1 — BASE vs CHAT MODELS
# ═══════════════════════════════════════════════════════════════════════════
#
# A base model (GPT, LLaMA-base) is trained with next-token prediction on
# raw internet text.  It's a *completion engine*, not a chat assistant.
#
# Ask it "What is the capital of France?" and it might continue with
# ten more quiz questions, because that's what similar text looked like
# in its training data.
#
# SFT teaches the model a new pattern: given an instruction, produce a
# helpful answer — not just a likely continuation.
# ═══════════════════════════════════════════════════════════════════════════

print("=" * 72)
print("PART 1: BASE vs CHAT MODELS")
print("=" * 72)


"""
WHY THIS MATTERS:
Without SFT, a base model is useless as an assistant.  It completes text
but doesn't follow instructions.  ChatGPT = GPT-base + SFT + RLHF.
The SFT step is what gives the model its "personality" and ability to
follow user requests.
"""

# Simulate a tiny "base model" that learned token co-occurrence patterns
vocab = ["What", "is", "the", "capital", "of", "France", "?",
         "Paris", "London", "Berlin", ".", "Who", "wrote", "How"]
vocab_size = len(vocab)
word2id = {w: i for i, w in enumerate(vocab)}

torch.manual_seed(42)
base_logits = torch.randn(vocab_size)  # random logits for next token

# A base model just picks whatever token is most probable in context.
# It doesn't "know" it should answer — it just continues the text.
base_probs = F.softmax(base_logits, dim=-1)
base_top5 = torch.topk(base_probs, 5)

print("\nPrompt: 'What is the capital of France?'")
print("\nBase model next-token predictions (no SFT):")
for prob, idx in zip(base_top5.values, base_top5.indices):
    print(f"  {vocab[idx]:>10s}  {prob:.4f}")
print("  → Base model just continues text — might output 'Who', 'How', etc.")

# After SFT, the model learns to produce the answer token
sft_logits = base_logits.clone()
sft_logits[word2id["Paris"]] = 5.0     # SFT boosts the correct answer
sft_logits[word2id["Who"]] = -2.0      # suppresses continuation patterns
sft_logits[word2id["How"]] = -2.0

sft_probs = F.softmax(sft_logits, dim=-1)
sft_top5 = torch.topk(sft_probs, 5)

print("\nAfter SFT — model learns to answer:")
for prob, idx in zip(sft_top5.values, sft_top5.indices):
    print(f"  {vocab[idx]:>10s}  {prob:.4f}")
print("  → SFT teaches: instruction in → helpful answer out.")

# The key difference in numbers
print(f"\nP('Paris' | base):  {base_probs[word2id['Paris']]:.4f}")
print(f"P('Paris' | SFT):   {sft_probs[word2id['Paris']]:.4f}")
print(f"Boost factor: {sft_probs[word2id['Paris']] / base_probs[word2id['Paris']]:.1f}x")


