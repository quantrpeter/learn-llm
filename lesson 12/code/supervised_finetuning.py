# PART 6 — QLoRA CONCEPT
# ═══════════════════════════════════════════════════════════════════════════
#
# QLoRA = Quantized base weights + LoRA adapters on top.
#
# The idea: since we freeze the base weights anyway, why store them in
# FP16?  Quantize to 4-bit (NF4) → 4× memory savings on the frozen part.
# LoRA adapters stay in FP16/BF16 for training stability.
#
# This is how you fine-tune a 65B model on a single 48 GB GPU.
# ═══════════════════════════════════════════════════════════════════════════

