# PART 3 — CHAT TEMPLATES
# ═══════════════════════════════════════════════════════════════════════════
#
# Raw text needs structure.  Chat templates define how to pack system
# messages, user inputs, and assistant responses into a single token
# sequence the model can learn from.
#
# Different model families use different templates:
#   - ChatML:  <|im_start|>role\n...<|im_end|>
#   - LLaMA:   <s>[INST] ... [/INST]
#   - Alpaca:  ### Instruction:\n...\n### Response:\n
#
# The model never "sees" roles natively — it just sees tokens.
# The template is how we ENCODE role information into the token stream.
# ═══════════════════════════════════════════════════════════════════════════

print("\n" + "=" * 72)
print("PART 3: CHAT TEMPLATES")
print("=" * 72)

"""
WHY THIS MATTERS:
If you use the wrong template at inference time (different from training),
the model won't know where instructions end and answers begin.  Template
mismatch is the #1 cause of fine-tuned models "not working."
"""


# --- 3.1 ChatML format (used by Qwen, Yi, many others) --------------------

def format_chatml(messages):
    """Format messages using ChatML template."""
    formatted = ""
    for msg in messages:
        formatted += f"<|im_start|>{msg['role']}\n{msg['content']}<|im_end|>\n"
    formatted += "<|im_start|>assistant\n"
    return formatted


# --- 3.2 LLaMA-2 chat format ----------------------------------------------

def format_llama2(messages):
    """Format messages using LLaMA-2 chat template."""
    system_msg = ""
    formatted = "<s>"
    for msg in messages:
        if msg["role"] == "system":
            system_msg = msg["content"]
        elif msg["role"] == "user":
            if system_msg:
                formatted += f"[INST] <<SYS>>\n{system_msg}\n<</SYS>>\n\n{msg['content']} [/INST]"
                system_msg = ""
            else:
                formatted += f"[INST] {msg['content']} [/INST]"
        elif msg["role"] == "assistant":
            formatted += f" {msg['content']} </s><s>"
    return formatted


# --- 3.3 Simple Alpaca format (no special tokens needed) -------------------

def format_alpaca(instruction, input_text="", output_text=""):
    """Format using Alpaca template."""
    if input_text:
        prompt = (f"Below is an instruction that describes a task, paired "
                  f"with further context.\n\n"
                  f"### Instruction:\n{instruction}\n\n"
                  f"### Input:\n{input_text}\n\n"
                  f"### Response:\n")
    else:
        prompt = (f"Below is an instruction that describes a task.\n\n"
                  f"### Instruction:\n{instruction}\n\n"
                  f"### Response:\n")
    if output_text:
        prompt += output_text
    return prompt


